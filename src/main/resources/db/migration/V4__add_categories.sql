CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) UNIQUE NOT NULL,

    CONSTRAINT chk_categories_name_is_not_blank
                        CHECK (length(trim(name)) > 0)
);

